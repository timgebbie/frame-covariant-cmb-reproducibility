#!/usr/bin/env python3
r"""F8 — where each coupling sits in the hierarchy, and which release carries it.

    python scripts/figure_f8_schematic.py

**No data.** This is the one released figure that computes nothing: it is a
statement about the *structure* of the exact divergence hierarchy, read off the
equations rather than measured. It is generated by a script anyway, like every
other figure, so that the manifest covers it and its caption can name a
producing script — a hand-drawn diagram is the one artefact that can drift
without any gate noticing.

**What it is for.** A reader arriving from the paper needs to know which
couplings this release actually integrates and which are asserted to be absent.
That question has a precise answer, and it is a picture rather than a paragraph:

* **Free streaming**, (F.1)–(F.4): couples rank $\ell$ to $\ell\pm1$ and nothing
  else. It is the whole of v1.0.0's hierarchy, and the reason the Appendix F
  chain is the acceptance spine.
* **Thomson scattering**: acts only at $\ell\le2$ — the monopole it cannot
  change, the dipole through $v_B$, the quadrupole through the anisotropic
  stress. Every higher rank is reached only by free streaming.
* **The acceleration pair**, $O(\varepsilon^2\ell)$ in the Newtonian frame:
  $\ell\to\ell\pm1$, because $K^a=\mathrm D^a\Phi_A$ carries no direction
  dependence of its own.
* **The shear triple**, $O(\varepsilon^2\ell)$ in the CDM frame:
  $\ell\to\ell\pm2$ *and* a rank-preserving $\ell\to\ell$, because
  $K^a=\sigma^a{}_be^b$ does depend on direction. The rank-preserving coupling
  exists **only** when $K^a$ does, which is the one structural difference
  between the two frames.

The last two are the same operator $K_\perp^a\partial/\partial e^a$ in two
frames, and the number of ranks each reaches is set by whether $K^a$ depends
on the photon direction. **That is the whole content of the frame argument, and
it is visible here before any of it is computed.**

**Decision S9 is drawn as well as asserted.** v1.0.0 carries no $O(\ell)$
coupling: every coupling in the solid half is a ratio of linear polynomials and
tends to a constant, so a v1.5.0 coupling wired in early would acquire a factor
of $\ell$ and fail `tests/test_appendix_f_chain.py`. The dashed half is what
arrives later, and it is dashed for that reason rather than for emphasis.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import FancyArrowPatch  # noqa: E402

from functions.plotting.style import (  # noqa: E402
    INK,
    SERIES,
    save_figure,
    use_house_style,
)

RANKS = [(2, r"$\ell+2$"), (1, r"$\ell+1$"), (0, r"$\ell$"),
         (-1, r"$\ell-1$"), (-2, r"$\ell-2$")]

#: One column per coupling family. **Three columns, not two overlaid.** The
#: first draft put the acceleration and shear arcs on a single x, where the
#: $\ell\pm1$ and $\ell\pm2$ arcs crossed and the rank-preserving loop was
#: unreadable. A schematic whose arrows cannot be followed has failed at the one
#: thing it exists to do.
COLUMNS = [
    {"x": 0.0, "slot": 1, "dashed": False,
     "reaches": [(0, 1), (0, -1)], "self_loop": False,
     "head": "in v1.0.0",
     "label": "free streaming\n(F.1)–(F.4)\n$\\ell\\pm1$"},
    {"x": 1.25, "slot": 2, "dashed": True,
     "reaches": [(0, 1), (0, -1)], "self_loop": False,
     "head": "arrives later",
     "label": "acceleration pair\nNewtonian frame\n$\\ell\\pm1$"},
    {"x": 2.5, "slot": 3, "dashed": True,
     "reaches": [(0, 2), (0, -2)], "self_loop": True,
     "head": "",
     "label": "shear triple\nCDM frame\n$\\ell\\pm2$, and $\\ell\\to\\ell$"},
]

LEFT, RIGHT = -0.45, 2.95


def _arc(ax, x, y0, y1, *, colour, dashed, bend, lw=1.6):
    ax.add_patch(FancyArrowPatch(
        (x, y0), (x, y1), connectionstyle=f"arc3,rad={bend}",
        arrowstyle="-|>", mutation_scale=11, lw=lw, color=colour,
        linestyle=(0, (4, 2)) if dashed else "solid",
        shrinkA=3, shrinkB=3, zorder=3,
    ))


def draw() -> plt.Figure:
    use_house_style()
    fig, ax = plt.subplots(figsize=(6.6, 4.4))
    fig.subplots_adjust(top=0.74, bottom=0.21, left=0.11, right=0.97)

    for y, label in RANKS:
        ax.plot([LEFT, RIGHT], [y, y], color=INK["grid"], lw=0.8, zorder=1)
        ax.text(LEFT - 0.08, y, label, ha="right", va="center",
                fontsize=8.6, color=INK["primary"])

    for col in COLUMNS:
        colour = SERIES[col["slot"]]
        for a, b in col["reaches"]:
            bend = -0.5 if b > a else 0.5
            _arc(ax, col["x"], a, b, colour=colour, dashed=col["dashed"], bend=bend)
        if col["self_loop"]:
            ax.add_patch(FancyArrowPatch(
                (col["x"] + 0.10, 0.16), (col["x"] + 0.10, -0.16),
                connectionstyle="arc3,rad=-1.9", arrowstyle="-|>",
                mutation_scale=9, lw=1.4, color=colour,
                linestyle=(0, (4, 2)), zorder=3))
        if col["head"]:
            # "arrives later" spans two columns, so it is centred over the pair
            # rather than sitting above the first of them.
            hx = col["x"] if col["slot"] == 1 else (col["x"] + COLUMNS[-1]["x"]) / 2.0
            ax.text(hx, 2.95, col["head"], ha="center", va="center",
                    fontsize=8.2, color=INK["primary"])
        ax.text(col["x"], -3.00, col["label"], ha="center", va="top",
                fontsize=7.2, color=INK["secondary"])

    ax.set_xlim(LEFT - 0.55, RIGHT + 0.12)
    ax.set_ylim(-3.55, 3.30)
    ax.set_xticks([])
    ax.set_yticks([])
    for side in ("top", "right", "bottom", "left"):
        ax.spines[side].set_visible(False)

    fig.suptitle("F8   Where each coupling sits in the hierarchy",
                 x=0.012, y=0.965, ha="left", fontsize=10, color=INK["primary"])
    fig.text(
        0.012, 0.898,
        "Solid: what this release integrates. Dashed: what arrives later, and by "
        "which frame. The acceleration pair reaches\n$\\ell\\pm1$ because "
        "$K^a=\\mathrm{D}^a\\Phi_A$ carries no direction dependence; the shear "
        "triple reaches $\\ell\\pm2$ and preserves rank because\n"
        "$K^a=\\sigma^a_b e^b$ does. They are one operator in two frames — "
        "the frame argument, before anything is computed.",
        ha="left", va="top", fontsize=7.4, color=INK["secondary"],
    )
    fig.text(
        0.012, 0.030,
        "Thomson scattering acts only at $\\ell\\leq2$ — the monopole it cannot "
        "change, the dipole through $v_B$, the quadrupole through the\n"
        "anisotropic stress. Every higher rank is reached by free streaming "
        "alone, which is why the Appendix F chain is the acceptance spine.",
        ha="left", va="bottom", fontsize=7.0, color=INK["muted"],
    )
    return fig


def main() -> int:
    for p in save_figure(draw(), "f8-schematic", "v1.1.0"):
        print(f"wrote {p.relative_to(ROOT)}")
    print("  no data: this figure is a structural statement, not a measurement")
    return 0


if __name__ == "__main__":
    sys.exit(main())
