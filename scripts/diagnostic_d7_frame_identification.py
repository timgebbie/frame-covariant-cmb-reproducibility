#!/usr/bin/env python3
r"""D7 — how good is the identification of the CDM frame with the energy frame?

    python scripts/diagnostic_d7_frame_identification.py

**They are two stipulations, not one, and Paper 1 says so.** Paper 1 v1.1.0:

> The *energy frame* is the frame in which the total energy flux vanishes,
> $q_a=0$; it and the CDM frame [...] are separate stipulations, and they
> agree only to $\approx$ [...]. Setting $q_a=0$ in a mixture gives
> $\rho_{\!_C}v^a_{\!_C}+\tfrac43\rho_{\!_R}v^a_{\!_R}+\ldots=0$, so the energy
> frame tilts away from the CDM one by $O(\rho_{\!_R}/\rho_{\!_C})$ and the two
> coincide in the limit of matter domination.

***Annals II* enumerates them as separate choices**, in \S4.1, immediately
after the general frame transformations (31)--(37): *"there are three
particularly useful choices"* --- (1) **the energy frame**, $\tilde q_a=0$;
(2) **the zero acceleration frame (or CDM frame)**, $\tilde A_a\approx0$,
*"geodesic right through tight-coupling, slow decoupling and into the
free-streaming era"*; (3) **the Newtonian frame**, $\tilde\sigma_{ab}\approx0$.
**This bundle computes item 2 and labels it item 1.**

This bundle's decision **S8** said instead that the CDM frame **is** the
total-energy frame, with the reason *"CDM is pressureless and geodesic and
carries no energy flux of its own"*. That reason is about CDM alone. The frame
condition is about the **total**, and in the CDM rest frame the total is not
zero, because the baryons and the photons are moving. Finding **T-29**; amended by **S8a**, accepted 2026-10-14.

**What the bundle computes is the CDM frame**, not $q_a=0$:
`cdm_frame_shift` integrates $v'+\mathcal Hv=-k\Phi_A$, which comes from
$\tilde A_a=0$ --- the *geodesic* condition, which is what makes a congruence
the CDM's. So no number moves; the label does.

This script measures the gap, because *"they coincide in the limit of matter
domination"* is only useful next to how far from that limit the calculation
actually sits. With tight coupling $v_B=v_\gamma=\tilde\tau_1$, the flux seen
in the CDM rest frame is

    q_a|_CDM = ( rho_b + (4/3) rho_gamma ) tau_1 ,

so **the baryons tilt it too** --- they are not CDM and they move with the
photons. The smallness parameter Paper 1 names, $\rho_R/\rho_C$, is therefore
the radiation half of it.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from functions.spectra.acoustic import solve_acoustic  # noqa: E402
from functions.spectra.frame_transform import cdm_frame_shift  # noqa: E402
from functions.spectra.two_frame import build_environment  # noqa: E402

OMEGA_B_H2 = 0.0224
OMEGA_GAMMA_H2 = 2.47e-5
H0 = 0.5                      # the bundle's fiducial h for the CDM model
K_COM = (5.0, 20.0, 60.0, 140.0, 300.0)

#: The Planck 2018 VI Table 2 column `provenance/COSMOLOGICAL-PARAMETERS-v1.md`
#: stamps, carried here so the second row of the summary is the real universe
#: and not this release's round numbers.
PLANCK = {"omega_b_h2": 0.02237, "omega_c_h2": 0.1200, "z_star": 1089.92}


def report() -> list[str]:
    env = build_environment(float(max(K_COM)), line_of_sight_weight="opacity")
    eta, eta_star, bg, a = env.eta, env.eta_star, env.background, env.a

    omega_m = H0**2
    f_b = OMEGA_B_H2 / omega_m
    rho_m = env.rho
    rho_b = f_b * rho_m
    rho_g = (OMEGA_GAMMA_H2 / omega_m) / a * rho_m
    inertia = rho_m + rho_g / 3.0            # rho + p
    i = int(np.argmin(np.abs(eta - eta_star)))

    radiation = (4.0 / 3.0) * rho_g[i]
    baryon = rho_b[i]
    lines = [
        "D7 — the CDM frame against the energy frame",
        "Generated by scripts/diagnostic_d7_frame_identification.py. "
        "Do not edit by hand.",
        "",
        "  Annals II section 4.1 lists them as two of THREE distinct choices:",
        "  (1) the energy frame, q~_a = 0; (2) the zero acceleration frame, or",
        "  CDM frame, A~_a = 0, 'geodesic right through tight-coupling, slow",
        "  decoupling and into the free-streaming era'; (3) the Newtonian frame.",
        "  Paper 1 v1.1.0 makes them separate stipulations agreeing only to",
        "  O(rho_R/rho_C). Decision S8 says they are the same thing. They are",
        "  not. This bundle computes item 2 and labels it item 1. Finding T-29.",
        "",
        "  This release's background (Einstein-de Sitter, h = 0.5), at eta_*:",
        f"    rho_b / rho_m                  {f_b:.4f}",
        f"    rho_R / rho_m                  {rho_g[i] / rho_m[i]:.4f}",
        f"    Paper 1's named parameter      {rho_g[i] / rho_m[i]:.3f}   "
        "(the radiation half)",
        f"    the full tilt parameter        "
        f"{(baryon + radiation) / rho_m[i]:.3f}   "
        "(rho_b + 4/3 rho_R) / rho_C",
        f"    baryon share of the tilt       "
        f"{baryon / (baryon + radiation):.2f}",
        "",
    ]

    # The same two numbers for the stamped Planck column, where the identification
    # is **worse**, because rho_c is a third of the total matter there and is not
    # lumped with the baryons as an Einstein-de Sitter background lumps them.
    p_rb = PLANCK["omega_b_h2"] / PLANCK["omega_c_h2"]
    p_rr = (OMEGA_GAMMA_H2 / PLANCK["omega_c_h2"]) * (1.0 + PLANCK["z_star"])
    lines += [
        "  Planck 2018 VI Table 2, at its own z_* "
        f"= {PLANCK['z_star']:.2f}:",
        f"    rho_b / rho_C                  {p_rb:.4f}",
        f"    rho_R / rho_C                  {p_rr:.4f}",
        f"    the full tilt parameter        {p_rb + 4.0 / 3.0 * p_rr:.3f}",
        "",
        "  So the identification is worst exactly where the acoustic physics is,",
        "  and improves afterwards on both counts: rho_R/rho_C falls, and after",
        "  decoupling the baryons stop moving with the photons and start moving",
        "  with the CDM, which removes their share of the tilt entirely.",
        "",
        f"  The tilt as a fraction of the Newtonian-to-CDM frame velocity v,",
        f"  over eta_* <= eta <= eta_0:",
        "",
        f"    {'k_com':>8} {'max|v|':>13} {'max|tilt|':>13} {'ratio':>8}",
    ]

    worst = 0.0
    window = eta >= eta_star
    inside = eta <= min(float(bg.eta_0), 6.0 * eta_star)
    for k in K_COM:
        acoustic = solve_acoustic(
            float(k), eta[inside], background=bg, phi_a=env.phi_a[inside],
            phi_h=env.phi_h[inside], omega_b_h2=OMEGA_B_H2,
            expansion_coupling=False)
        tau_1 = np.empty_like(eta)
        tau_1[inside], tau_1[~inside] = acoustic.tau_1, acoustic.tau_1[-1]
        # tau_1 is carried as v_B/k; the tilt is a velocity, so restore the k.
        tilt = (rho_b + (4.0 / 3.0) * rho_g) * (float(k) * tau_1) / inertia
        v = cdm_frame_shift(eta, env.phi_a, float(k), background=bg).v
        ratio = np.max(np.abs(tilt[window])) / np.max(np.abs(v[window]))
        worst = max(worst, ratio)
        lines.append(f"    {k:8.1f} {np.max(np.abs(v[window])):13.3e} "
                     f"{np.max(np.abs(tilt[window])):13.3e} {ratio:8.3f}")

    lines += [
        "",
        f"  worst over the grid: {worst:.1%}",
        "",
        "  **No released number moves.** The bundle integrates v' + Hv = -k Phi_A,",
        "  which comes from A~_a = 0 — the geodesic condition, and geodesic is what",
        "  makes a congruence the CDM's. The frame it computes is the CDM frame",
        "  throughout, which is the one Paper 1 uses. What is wrong is the label,",
        "  and a label is not a small thing here: S8 exists because 'CDM' named",
        "  both a model and a frame, and S13 exists because 'lambda' named three",
        "  things two rows apart.",
        "",
        "  Annals II's own name for what this bundle computes is the ZERO",
        "  ACCELERATION FRAME, or CDM frame -- section 4.1, item 2 of three.",
        "  Proposed as S8a; the amendment is the PI's, because S8 is a decision.",
    ]
    return lines


def main() -> int:
    lines = report()
    print("\n".join(lines))
    out = ROOT / "diagnostics" / "d7-frame-identification-v1.2.0.txt"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"\nwrote {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
